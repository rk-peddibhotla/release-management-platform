
-- =========================================================
-- V1: Initial database schema
-- Release & Change Management Platform
-- =========================================================


-- 1. USERS
-- =========================================================

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_users_role
        CHECK (role IN ('ADMIN', 'ENGINEER', 'APPROVER')),

    CONSTRAINT chk_users_email_lowercase
        CHECK (email = LOWER(email))
);


-- 2. APPLICATIONS
-- =========================================================

CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 3. ENVIRONMENTS
-- =========================================================

CREATE TABLE environments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    name VARCHAR(50) NOT NULL,
    environment_type VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_environments_application
        FOREIGN KEY (application_id)
        REFERENCES applications(id),

    CONSTRAINT uq_environments_application_name
        UNIQUE (application_id, name),

    CONSTRAINT chk_environments_type
        CHECK (
            environment_type IN (
                'DEVELOPMENT',
                'TESTING',
                'STAGING',
                'PRODUCTION'
            )
        )
);


-- 4. RELEASES
-- =========================================================

CREATE TABLE releases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment_id BIGINT NOT NULL,
    version VARCHAR(50) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    scheduled_at TIMESTAMPTZ NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_releases_environment
        FOREIGN KEY (environment_id)
        REFERENCES environments(id),

    CONSTRAINT fk_releases_created_by
        FOREIGN KEY (created_by)
        REFERENCES users(id),

    CONSTRAINT uq_releases_environment_version
        UNIQUE (environment_id, version),

    -- Supports the composite foreign key from change_requests.
    CONSTRAINT uq_releases_id_environment
        UNIQUE (id, environment_id),

    CONSTRAINT chk_releases_status
        CHECK (
            status IN (
                'SCHEDULED',
                'IN_PROGRESS',
                'COMPLETED',
                'CANCELLED'
            )
        )
);


-- 5. CHANGE REQUESTS
-- =========================================================

CREATE TABLE change_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment_id BIGINT NOT NULL,
    release_id BIGINT,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    change_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    requested_by BIGINT NOT NULL,
    planned_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_change_requests_environment
        FOREIGN KEY (environment_id)
        REFERENCES environments(id),

    CONSTRAINT fk_change_requests_release_environment
        FOREIGN KEY (release_id, environment_id)
        REFERENCES releases(id, environment_id),

    CONSTRAINT fk_change_requests_requested_by
        FOREIGN KEY (requested_by)
        REFERENCES users(id),

    CONSTRAINT chk_change_requests_type
        CHECK (
            change_type IN (
                'FEATURE',
                'BUG_FIX',
                'CONFIGURATION',
                'PATCH'
            )
        ),

    CONSTRAINT chk_change_requests_status
        CHECK (
            status IN (
                'DRAFT',
                'SUBMITTED',
                'APPROVED',
                'REJECTED'
            )
        ),

    CONSTRAINT chk_change_requests_release_approval
        CHECK (
            release_id IS NULL OR status = 'APPROVED'
        )
);


-- 6. APPROVALS
-- =========================================================

CREATE TABLE approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_request_id BIGINT NOT NULL UNIQUE,
    approver_id BIGINT NOT NULL,
    decision VARCHAR(20) NOT NULL,
    comments TEXT,
    decided_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_approvals_change_request
        FOREIGN KEY (change_request_id)
        REFERENCES change_requests(id),

    CONSTRAINT fk_approvals_approver
        FOREIGN KEY (approver_id)
        REFERENCES users(id),

    CONSTRAINT chk_approvals_decision
        CHECK (decision IN ('APPROVED', 'REJECTED'))
);


-- 7. DEPLOYMENTS
-- =========================================================

CREATE TABLE deployments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id BIGINT NOT NULL,
    attempt_number INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    deployed_by BIGINT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ NOT NULL,
    notes TEXT,

    CONSTRAINT fk_deployments_release
        FOREIGN KEY (release_id)
        REFERENCES releases(id),

    CONSTRAINT fk_deployments_deployed_by
        FOREIGN KEY (deployed_by)
        REFERENCES users(id),

    CONSTRAINT uq_deployments_release_attempt
        UNIQUE (release_id, attempt_number),

    CONSTRAINT chk_deployments_attempt_number
        CHECK (attempt_number > 0),

    CONSTRAINT chk_deployments_status
        CHECK (status IN ('SUCCESS', 'FAILED')),

    CONSTRAINT chk_deployments_timestamps
        CHECK (completed_at >= started_at)
);


-- 8. AUDIT LOGS
-- =========================================================

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    entity_type VARCHAR(50) NOT NULL,
    entity_id BIGINT NOT NULL,
    action VARCHAR(50) NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_audit_logs_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    CONSTRAINT chk_audit_logs_details
        CHECK (JSONB_TYPEOF(details) = 'object')
);


-- INDEXES
-- =========================================================

CREATE INDEX idx_releases_environment_status
    ON releases(environment_id, status);

CREATE INDEX idx_change_requests_environment_status
    ON change_requests(environment_id, status);

CREATE INDEX idx_change_requests_requested_by
    ON change_requests(requested_by);

CREATE INDEX idx_change_requests_release_environment
    ON change_requests(release_id, environment_id);

CREATE INDEX idx_approvals_approver
    ON approvals(approver_id);

CREATE INDEX idx_audit_logs_entity
    ON audit_logs(entity_type, entity_id, created_at);

CREATE INDEX idx_audit_logs_user
    ON audit_logs(user_id);
